// Rebuilds public/icons.js from the lucide-static devDependency, inlining ONLY the icons the app uses,
// so the browser never loads node_modules. Run: node scripts/make-icon-module.mjs
//
// To add an icon: append its Lucide name (see https://lucide.dev/icons or node_modules/lucide-static/icons)
// to NAMES below, map an app concept to it in CONCEPTS if needed, and re-run this script.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const pkgDir = path.dirname(require.resolve('lucide-static/package.json'));
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const licence = fs.readFileSync(path.join(pkgDir, 'LICENSE'), 'utf8').trim();

// App concept (screen id / action) -> Lucide icon name.
const CONCEPTS = {
  home: 'house', chart: 'layout-grid', panchangam: 'book-open', roadmap: 'route', health: 'heart-pulse', guide: 'compass',
  seva: 'landmark', priests: 'flame', store: 'shopping-bag', packages: 'luggage', peyarchi: 'orbit',
  vratham: 'sparkles', life: 'telescope', chat: 'message-circle', ask: 'circle-help',
  couple: 'heart-handshake', porutham: 'heart', gunamilan: 'calculator', partners: 'handshake',
  vargas: 'grid-3x3', numerology: 'hash', muhurtham: 'calendar-check', calendar: 'calendar-days',
  analysis: 'scroll-text', relations: 'users', parigaram: 'flame-kindling', temples: 'landmark',
  mantras: 'music', weather: 'cloud-sun', reminders: 'alarm-clock', names: 'baby', thivasam: 'hand-heart',
  starbday: 'cake', ruthu: 'flower-2', live: 'moon-star', about: 'info', more: 'menu', vehicle: 'car',
  plans: 'crown', family: 'users-round', settings: 'settings', share: 'share-2', print: 'printer',
  speak: 'volume-2', back: 'chevron-left', next: 'chevron-right', location: 'map-pin', sun: 'sun',
  moon: 'moon', star: 'star', clock: 'clock', phone: 'phone', search: 'search', check: 'check',
  alert: 'triangle-alert', lock: 'lock', download: 'download', plus: 'plus', invite: 'gift',
  feedback: 'star', legal: 'file-text', admin: 'shield-check', user: 'user',
  // Thunai navigation (five destinations) and new screens.
  today: 'sun', mychart: 'layout-grid', plan: 'calendar-range', ask_thunai: 'message-circle',
  matching: 'heart-handshake', templeplan: 'map', safeguards: 'shield', account: 'circle-user-round',
  coins: 'coins', sprout: 'sprout', home_icon: 'house-heart', expand: 'chevron-down', close: 'x', map_pin: 'map-pinned',
};
// Colour group for each navigation concept -> class ic-<group> on the icon chip (styled in styles.css).
const GROUPS = {
  daily: ['panchangam', 'calendar', 'muhurtham', 'vratham', 'live', 'weather', 'reminders', 'templeplan'],
  personal: ['roadmap', 'health', 'guide', 'life', 'analysis', 'vargas', 'numerology', 'peyarchi', 'starbday', 'family'],
  match: ['couple', 'porutham', 'gunamilan', 'partners', 'relations', 'matching'],
  spiritual: ['parigaram', 'mantras', 'temples', 'thivasam', 'names', 'ruthu'],
  services: ['seva', 'priests', 'store', 'packages', 'plans', 'invite'],
  help: ['chat', 'ask', 'about', 'feedback', 'legal', 'admin', 'safeguards'],
};
const GROUP_OF = Object.fromEntries(Object.entries(GROUPS).flatMap(([g, ids]) => ids.map((id) => [id, g])));
// Extra raw names to inline even if no concept points at them.
const EXTRA = ['sparkle', 'leaf'];

const NAMES = [...new Set([...Object.values(CONCEPTS), ...EXTRA])].sort();

const body = (name) => {
  const svg = fs.readFileSync(path.join(pkgDir, 'icons', `${name}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '');
  return inner.split('\n').map((l) => l.trim()).filter(Boolean).join('').replace(/\s*\/>/g, '/>');
};

const paths = Object.fromEntries(NAMES.map((n) => [n, body(n)]));
let out = `// GENERATED by scripts/make-icon-module.mjs from lucide-static v${version} — do not edit by hand.
// Line icons for navigation (home quick row, tiles, tab bar, More menu). Rendered inline, no runtime deps.
/*
 * Lucide icons (https://lucide.dev)
${licence.split('\n').map((l) => ` * ${l}`.trimEnd()).join('\n')}
 */

const P = ${JSON.stringify(paths, null, 0).replace(/","/g, '",\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, ',\n}')};

/** App concept -> icon name. */
export const ICONS = ${JSON.stringify(CONCEPTS, null, 2).replace(/"([a-z]\w*)":/g, '$1:')};

/** Concept -> chip colour group (daily | personal | match | spiritual | services | help). */
export const ICON_GROUP = ${JSON.stringify(GROUP_OF, null, 2).replace(/"([a-z]\w*)":/g, '$1:')};

/** Inline SVG string for a Lucide icon name (or an ICONS concept key). Unknown names render an empty box. */
export function icon(name, { size = 24, cls = '' } = {}) {
  const d = P[name] ?? P[ICONS[name]] ?? '';
  return \`<svg class="ic\${cls ? \` \${cls}\` : ''}" viewBox="0 0 24 24" width="\${size}" height="\${size}" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">\${d}</svg>\`;
}
`;
out += `
/** Icon inside a rounded chip: <span class="ic-chip ic-<group> extra">svg</span>. */
export function iconChip(id, { size = 24, cls = '' } = {}) {
  return \`<span class="\${cls ? \`\${cls} \` : ''}ic-chip ic-\${ICON_GROUP[id] || 'help'}">\${icon(ICONS[id] || id, { size })}</span>\`;
}
`;
fs.writeFileSync(new URL('../public/icons.js', import.meta.url), out);
console.log(`public/icons.js: ${NAMES.length} icons`);
