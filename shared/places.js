export const PLACES = RAW.map(([name, region, lat, lon, tz]) => ({ name, region, lat, lon, tz }));

export function searchLocalPlaces(q, limit = 8) {
  const s = q.trim().toLowerCase();
  if (!s) return PLACES.slice(0, limit);
  const starts = PLACES.filter((p) => p.name.toLowerCase().startsWith(s));
  const contains = PLACES.filter((p) => !starts.includes(p) && `${p.name} ${p.region}`.toLowerCase().includes(s));
  return [...starts, ...contains].slice(0, limit);
}

