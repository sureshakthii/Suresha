// Generates the native launcher icons and splash screens from public/icon.svg (via scripts/brand-art.mjs).
//   Android: mipmap-*/ic_launcher.png            legacy square icon (pre-Android 8)
//            mipmap-*/ic_launcher_round.png      legacy round icon
//            mipmap-*/ic_launcher_foreground.png adaptive foreground: the lamp-and-arch mark ONLY, transparent,
//                                                inside the 66 dp safe circle of the 108 dp canvas (no tile — the
//                                                launcher supplies the shape; a tile here made an "icon in an icon")
//            mipmap-*/ic_launcher_monochrome.png Android 13+ themed icon (alpha silhouette, same placement)
//            drawable*/splash.png                legacy splash: the mark on the launch colour
//            values/ic_launcher_background.xml   launch colour + icon background colours
//            (the adaptive background itself is drawable[-v24]/ic_launcher_background.xml — brand gradient)
//   iOS:     AppIcon-512@2x.png (1024, full-bleed, iOS rounds the corners) and Splash.imageset (2732²)
// Writes previews (circle / squircle / rounded-square masks, themed, splash) to dist/icon-preview.png (not committed)
// unless --no-preview. Uses the Playwright Chromium already installed.
// Usage: npm run mobile:icons   (re-run whenever the logo changes)
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
import { art, COLORS, root, renderPng } from '../scripts/brand-art.mjs';

const androidRes = path.join(root, 'android', 'app', 'src', 'main', 'res');
const iosAssets = path.join(root, 'ios', 'App', 'App', 'Assets.xcassets');
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const SPLASH = {
  'drawable': [480, 320],
  'drawable-port-mdpi': [320, 480], 'drawable-port-hdpi': [480, 800], 'drawable-port-xhdpi': [720, 1280],
  'drawable-port-xxhdpi': [960, 1600], 'drawable-port-xxxhdpi': [1280, 1920],
  'drawable-land-mdpi': [480, 320], 'drawable-land-hdpi': [800, 480], 'drawable-land-xhdpi': [1280, 720],
  'drawable-land-xxhdpi': [1600, 960], 'drawable-land-xxxhdpi': [1920, 1280],
};

const browser = await chromium.launch();
const written = [];
const png = async (file, markup, opts) => { await renderPng(browser, markup, file, opts); written.push(path.relative(root, file)); };

const COLORS_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by mobile/make-native-icons.mjs — edit COLORS in scripts/brand-art.mjs instead. -->
<resources>
    <!-- Solid fallback for the adaptive icon background (drawable/ic_launcher_background.xml) -->
    <color name="ic_launcher_background">${COLORS.TILE_BOTTOM}</color>
    <!-- The ONE launch colour: system splash, window behind the WebView, status / navigation bar until the
         web app sets them from its theme (public/app.js syncStatusBar). Same as capacitor.config.json. -->
    <color name="thunai_launch_bg">${COLORS.SPLASH}</color>
</resources>
`;

if (fs.existsSync(androidRes)) {
  for (const [name, d] of Object.entries(DENSITIES)) {
    const dir = path.join(androidRes, `mipmap-${name}`);
    const legacy = Math.round(48 * d);
    const canvas = Math.round(108 * d);
    await png(path.join(dir, 'ic_launcher.png'), art.legacy(), { w: legacy, transparent: true });
    await png(path.join(dir, 'ic_launcher_round.png'), art.round(), { w: legacy, transparent: true });
    await png(path.join(dir, 'ic_launcher_foreground.png'), art.foreground(), { w: canvas, transparent: true });
    await png(path.join(dir, 'ic_launcher_monochrome.png'), art.monochrome(), { w: canvas, transparent: true });
  }
  for (const [dir, [w, h]] of Object.entries(SPLASH)) {
    await png(path.join(androidRes, dir, 'splash.png'), art.splash(w, h, Math.min(w, h) * 0.24), { w, h });
  }
  fs.writeFileSync(path.join(androidRes, 'values', 'ic_launcher_background.xml'), COLORS_XML);
  written.push('android/app/src/main/res/values/ic_launcher_background.xml');
} else {
  console.warn('⚠ android/ not found — run `npx cap add android` first.');
}

if (fs.existsSync(iosAssets)) {
  await png(path.join(iosAssets, 'AppIcon.appiconset', 'AppIcon-512@2x.png'), art.fullBleed(0.74), { w: 1024 });
  for (const name of ['splash-2732x2732.png', 'splash-2732x2732-1.png', 'splash-2732x2732-2.png']) {
    await png(path.join(iosAssets, 'Splash.imageset', name), art.splash(2732, 2732, 300), { w: 2732 });
  }
} else {
  console.warn('ℹ ios/ not found — skipping iOS icons.');
}

if (!process.argv.includes('--no-preview')) {
  // What launchers will show: background gradient + foreground under each mask, the themed icon, and the splash.
  const fg = `data:image/svg+xml;base64,${Buffer.from(art.foreground()).toString('base64')}`;
  const mono = `data:image/svg+xml;base64,${Buffer.from(art.monochrome()).toString('base64')}`;
  const squircle = "path('M96 0C172 0 192 20 192 96S172 192 96 192 0 172 0 96 20 0 96 0Z')";
  const tile = (clip, bg = `linear-gradient(${COLORS.TILE_TOP},${COLORS.TILE_BOTTOM})`, img = fg, filter = '') =>
    `<div style="width:192px;height:192px;clip-path:${clip};background:${bg};position:relative"><img src="${img}" style="position:absolute;left:-48px;top:-48px;width:288px;height:288px;${filter}"></div>`;
  const cell = (label, inner) => `<figure style="margin:0;text-align:center;color:#eee;font:14px sans-serif">${inner}<figcaption style="margin-top:8px">${label}</figcaption></figure>`;
  const html = `<html><body style="margin:0;padding:24px;background:#2b2b2b;display:flex;flex-wrap:wrap;gap:28px;width:1240px">
    ${cell('circle', tile('circle(50%)'))}
    ${cell('squircle', tile(squircle))}
    ${cell('rounded square', tile('inset(0 round 18%)'))}
    ${cell('teardrop', tile('inset(0 round 50% 50% 18% 50%)'))}
    ${cell('themed (Android 13)', tile('circle(50%)', '#d8e6c9', mono, 'filter:brightness(0) saturate(100%) invert(22%) sepia(18%) saturate(900%) hue-rotate(50deg)'))}
    ${cell('legacy square', `<img src="data:image/svg+xml;base64,${Buffer.from(art.legacy()).toString('base64')}" width="192">`)}
    ${cell('legacy round', `<img src="data:image/svg+xml;base64,${Buffer.from(art.round()).toString('base64')}" width="192">`)}
    ${cell('foreground layer (checkered = transparent)', `<div style="width:192px;height:192px;background:repeating-conic-gradient(#555 0 25%,#777 0 50%) 0 0/16px 16px;position:relative"><img src="${fg}" width="192"><div style="position:absolute;inset:${192 * 21 / 108}px;border:1px dashed #0f0;border-radius:50%"></div></div>`)}
    ${cell('splash (portrait)', `<img src="data:image/svg+xml;base64,${Buffer.from(art.splash(360, 640, 72)).toString('base64')}" width="180">`)}
  </body></html>`;
  const file = path.join(root, 'dist', 'icon-preview.png');
  await renderPng(browser, html, file, { w: 1290, h: 560, html: true });
  console.log(`ℹ preview: ${path.relative(root, file)}`);
}

await browser.close();
console.log(`✔ ${written.length} images written:\n  ${written.join('\n  ')}`);
